#ifndef S21_HELPERS_H_
#define S21_HELPERS_H_

#include "s21_decimal.h"

/**
 * @file s21_helpers.h
 * @brief Внутренние вспомогательные функции для работы с s21_decimal.
 * @note Эти функции не являются частью публичного API и не должны
 *       использоваться вне исходных файлов библиотеки s21_decimal.
 */

// Вспомогательная структура для вычислений без переполнения
typedef struct {
    uint32_t bits[6]; // 192 бита под мантиссу
    int scale;
    int sign;
} s21_big_decimal;

/* ======================================================================== */
/*                         ТИПЫ И ПЕРЕЧИСЛЕНИЯ                              */
/* ======================================================================== */

/**
 * @brief Режимы округления для внутренних функций.
 */
typedef enum {
  S21_ROUND_TRUNCATE = 0,  ///< Отбрасывание дробной части (округление к нулю)
  S21_ROUND_HALF_UP =
      1,  ///< Арифметическое округление (>= 0.5 округляется вверх)
  S21_ROUND_HALF_EVEN = 2  ///< Банковское округление (до ближайшего четного)
} s21_rounding_mode;

/* ======================================================================== */
/*               ИНИЦИАЛИЗАЦИЯ И РАБОТА СО СВОЙСТВАМИ (БИТАМИ)              */
/* ======================================================================== */

/**
 * @brief Обнуляет все биты числа (устанавливает мантиссу, знак и scale в 0).
 * @param value Указатель на число для обнуления.
 */
void s21_decimal_zero(s21_decimal *value);

/**
 * @brief Получает значение указанного бита мантиссы или служебных битов.
 * @param value Указатель на число.
 * @param bit_index Индекс бита (от 0 до 127).
 * @return int 1, если бит установлен, 0, если сброшен.
 */
int s21_get_bit(const s21_decimal *value, int bit_index);

/**
 * @brief Устанавливает или сбрасывает указанный бит.
 * @param value Указатель на число.
 * @param bit_index Индекс бита (от 0 до 127).
 * @param bit_value Новое значение бита (0 или 1).
 */
void s21_set_bit(s21_decimal *value, int bit_index, int bit_value);

/**
 * @brief Получает знак числа.
 * @param value Указатель на число.
 * @return int 1, если число отрицательное, 0, если положительное или ноль.
 */
int s21_get_sign(const s21_decimal *value);

/**
 * @brief Устанавливает знак числа.
 * @param value Указатель на число.
 * @param sign Значение знака (0 для +, 1 для -).
 */
void s21_set_sign(s21_decimal *value, int sign);

/**
 * @brief Получает текущий масштаб (scale) числа.
 * @param value Указатель на число.
 * @return int Текущий scale (от 0 до 28).
 */
int s21_get_scale(const s21_decimal *value);

/**
 * @brief Устанавливает масштаб (scale) числа.
 * @param value Указатель на число.
 * @param scale Новое значение scale (должно быть в диапазоне 0-28).
 */
void s21_set_scale(s21_decimal *value, int scale);

/* ======================================================================== */
/*                    ПРОВЕРКИ И СРАВНЕНИЕ МОДУЛЕЙ                          */
/* ======================================================================== */

/**
 * @brief Проверяет, равно ли число нулю (все биты мантиссы равны 0).
 * @param value Указатель на число.
 * @return int 1, если число равно 0, иначе 0.
 */
int s21_is_zero(const s21_decimal *value);

/**
 * @brief Сравнивает модули (абсолютные значения) двух чисел, игнорируя знак.
 * @note Масштаб (scale) при сравнении не учитывается. Сравниваются только 96
 * бит мантиссы.
 * @param a Указатель на первое число.
 * @param b Указатель на второе число.
 * @return int 1, если |a| > |b|; -1, если |a| < |b|; 0, если |a| == |b|.
 */
int s21_bigint_cmp_abs(const s21_decimal *a, const s21_decimal *b);

/* ======================================================================== */
/*               БАЗОВАЯ АРИФМЕТИКА 96-БИТНЫХ МАНТИСС (BIGINT)              */
/* ======================================================================== */

/**
 * @brief Складывает мантиссы двух чисел как беззнаковые 96-битные целые числа.
 * @note Знак и scale результата не изменяются этой функцией.
 * @param a Указатель на первое слагаемое.
 * @param b Указатель на второе слагаемое.
 * @param result Указатель на структуру для записи результата.
 * @return int S21_OK при успехе, S21_ERROR_TOO_LARGE при переполнении 96 бит.
 */
int s21_bigint_add(const s21_decimal *a, const s21_decimal *b,
                   s21_decimal *result);

/**
 * @brief Вычитает мантиссу b из мантиссы a как беззнаковые 96-битные числа.
 * @note Предполагается, что |a| >= |b|. Знак и scale результата не изменяются.
 * @param a Указатель на уменьшаемое.
 * @param b Указатель на вычитаемое.
 * @param result Указатель на структуру для записи результата.
 * @return int S21_OK при успехе.
 */
int s21_bigint_sub(const s21_decimal *a, const s21_decimal *b,
                   s21_decimal *result);

/**
 * @brief Делит 96-битную мантиссу числа на 10.
 * @note Критически важна для уменьшения scale и реализации округлений.
 * @param value Указатель на число (мантисса будет изменена).
 * @param remainder Указатель на переменную для записи остатка от деления (0-9).
 *                  Нужен для принятия решения об округлении.
 * @return int S21_OK при успехе, S21_ERROR_CALCULATION при ошибке (например,
 * NULL).
 */
int s21_div_mantissa_by_10(s21_decimal *value, int *remainder);

/* ======================================================================== */
/*                         БИТОВЫЕ СДВИГИ                                   */
/* ======================================================================== */

/**
 * @brief Сдвигает 96-битную мантиссу числа влево на указанное количество бит.
 * @note Знак и scale не изменяются. Биты, выходящие за пределы 96 бит,
 * теряются.
 * @param value Указатель на число.
 * @param shift_bits Количество бит для сдвига (0 <= shift_bits <= 96).
 */
void s21_bigint_shift_left(s21_decimal *value, int shift_bits);

/**
 * @brief Сдвигает 96-битную мантиссу числа вправо на указанное количество бит.
 * @note Знак и scale не изменяются. Освобождающиеся старшие биты заполняются
 * нулями.
 * @param value Указатель на число.
 * @param shift_bits Количество бит для сдвига (0 <= shift_bits <= 96).
 */
void s21_bigint_shift_right(s21_decimal *value, int shift_bits);

/* ======================================================================== */
/*               НОРМАЛИЗАЦИЯ И МАСШТАБИРОВАНИЕ (SCALE)                     */
/* ======================================================================== */

/**
 * @brief Приводит два числа к общему масштабу (scale) путем умножения мантиссы
 *        числа с меньшим scale на 10.
 * @note Возвращает ошибку, если в процессе умножения происходит переполнение
 *       96-битной мантиссы ИЛИ если scale достигает 28, а числа все еще не
 * выровнены.
 * @param a Указатель на первое число (будет изменено).
 * @param b Указатель на второе число (будет изменено).
 * @return int S21_OK при успехе, S21_ERROR_CALCULATION при невозможности
 * выравнивания.
 */
int s21_normalize(s21_decimal *a, s21_decimal *b);

/**
 * @brief Умножает мантиссу числа на 10 и увеличивает его scale на 1.
 * @note Используется внутри s21_normalize и конвертеров.
 * @param value Указатель на число.
 * @return int S21_OK при успехе, S21_ERROR_TOO_LARGE при переполнении 96 бит
 *         или если scale уже равен 28.
 */
int s21_mul_mantissa_by_10(s21_decimal *value);

/**
 * @brief Округляет число до заданного масштаба (target_scale) путем деления
 * на 10.
 * @param value Указатель на число (будет изменено: scale уменьшится, мантисса
 * разделится).
 * @param target_scale Целевой масштаб (0 <= target_scale <= 28).
 * @param mode Режим округления (S21_ROUND_TRUNCATE, S21_ROUND_HALF_UP,
 * S21_ROUND_HALF_EVEN).
 * @return int S21_OK при успехе, S21_ERROR_CALCULATION при некорректных
 * параметрах.
 */
int s21_round_to_scale(s21_decimal *value, int target_scale,
                       s21_rounding_mode mode);

/* ======================================================================== */
/*               ФУНКЦИИ ДЛЯ РАБОТЫ С S21_BIG_DECIMAL                    */
/* ======================================================================== */

/**
 * @brief Конвертирует стандартный тип s21_decimal в расширенный s21_big_decimal.
 * 
 * @param src Исходное число в формате s21_decimal.
 * @param dst Указатель на структуру s21_big_decimal, куда будет записан результат.
 *            Оставшиеся старшие биты мантиссы инициализируются нулями.
 */
void s21_to_big_decimal(s21_decimal src, s21_big_decimal *dst);

/**
 * @brief Умножает 192-битную мантиссу числа s21_big_decimal на 10.
 * 
 * @param value Указатель на число s21_big_decimal. Мантисса числа будет изменена.
 */
void s21_mul_big_mantissa_by_10(s21_big_decimal *value);

/**
 * @brief Нормализует два числа в формате s21_big_decimal (уравнивает их scale).
 * 
 * Функция умножает мантиссу числа с меньшим масштабом на 10 и увеличивает
 * его масштаб на 1, пока масштабы обоих чисел не станут равны. Переполнение
 * исключено благодаря 192-битной мантиссе.
 * 
 * @param a Указатель на первое число s21_big_decimal (будет изменено при необходимости).
 * @param b Указатель на второе число s21_big_decimal (будет изменено при необходимости).
 */
void s21_normalize_big(s21_big_decimal *a, s21_big_decimal *b);

/**
 * @brief Сравнивает модули (мантиссы) двух чисел формата s21_big_decimal.
 *
 * Сравнение происходит покомпонентно от старшего 32-битного элемента (bits[5])
 * к младшему (bits[0]). Позволяет определить, чья мантисса больше по абсолютному значению.
 *
 * @param a Указатель на первое число s21_big_decimal.
 * @param b Указатель на второе число s21_big_decimal.
 * @return int 1, если |a| > |b|;
 *            -1, если |a| < |b|;
 *             0, если мантиссы равны (|a| == |b|).
 */
int s21_cmp_big_mantissa(const s21_big_decimal *a, const s21_big_decimal *b);


#endif  // S21_HELPERS_H_